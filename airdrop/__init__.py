'AirDrop —— 基于 PX4 + MAVSDK 的固定翼无人机空投系统（先侦查后空投）。\n\n规划中（按计划阶段推进）：``targeting``（目标统计）、``ballistics``（弹道）、\n``mission``（任务编排）。\n\n核心约定（迁移自 2.x，继续有效）\n--------------------------------\n1. MAVSDK 跑在专用线程里、持有自己的 asyncio 循环；指令经其队列串行执行。\n2. 遥测是"最新可用值合并"的快照；按时间查询走定采样率历史 + 内插/外推。\n3. 图传每一帧都交给 sink（**一帧不丢**）；``read()``/``latest()`` 是允许丢帧的实时路径。\n4. 帧按"收到时间 − 链路延时"还原拍摄时刻，再按该时刻取遥测（见 ``video.align``）。\n5. 对齐结果（画面 + 拍摄时刻遥测）进 FIFO 环形缓冲，供感知/记录等读者异步消费。\n6. 坐标解算用**标定产出**的相机→机体外参，不用硬编码安装角（见 ``georef.camera``）。\n'

